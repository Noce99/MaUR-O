#[cfg(test)]
mod tests {
    use super::*;

    /// Ids are what `--service` picks by, so each must be unique, and a
    /// service must be usable as written.
    #[test]
    fn every_service_is_well_formed() {
        for (i, service) in SERVICES.iter().enumerate() {
            assert!(
                SERVICES[..i].iter().all(|other| other.id != service.id),
                "{} is listed twice",
                service.id
            );
            assert!(
                service.url.ends_with('?') || service.url.ends_with('&'),
                "{}",
                service.id
            );
            assert!(service.ground_resolution > 0.0, "{}", service.id);
            assert!(service.max_tile_size >= 256, "{}", service.id);
            let c = service.coverage;
            assert!(
                c.min_lon < c.max_lon && c.min_lat < c.max_lat,
                "{}",
                service.id
            );
            assert!(!service.attribution.is_empty(), "{}", service.id);
            assert!(
                service.version == "1.1.1" || service.version == "1.3.0",
                "{}",
                service.id
            );
        }
    }
}
